const applyLanguage = (lang) => {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (translations[lang][key]) el.textContent = translations[lang][key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (translations[lang][key]) el.placeholder = translations[lang][key];
  });
  document.getElementById("lang-id").classList.toggle("active", lang === "id");
  document.getElementById("lang-en").classList.toggle("active", lang === "en");
  localStorage.setItem("portfolio-lang", lang);
};

document.getElementById("lang-id").addEventListener("click", () => applyLanguage("id"));
document.getElementById("lang-en").addEventListener("click", () => applyLanguage("en"));
applyLanguage(localStorage.getItem("portfolio-lang") || "id");

const menuBtn = document.getElementById("menu-btn");
const navLinks = document.getElementById("navbarNav");
menuBtn.addEventListener("click", () => navLinks.classList.toggle("open"));
navLinks.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => navLinks.classList.remove("open"));
});

const header = document.getElementById("navbar-top");
window.addEventListener("scroll", () => {
  header.classList.toggle("scrolled", window.scrollY > 12);
});

document.querySelectorAll(".filter-btn").forEach((btn) => {
  btn.addEventListener("click", () => {
    document.querySelectorAll(".filter-btn").forEach((b) => b.classList.remove("active"));
    btn.classList.add("active");
    const filter = btn.dataset.filter;
    document.querySelectorAll(".project-card").forEach((card) => {
      const hide = filter !== "all" && card.dataset.category !== filter;
      card.classList.toggle("hidden", hide);
      card.toggleAttribute("hidden", hide);
    });
  });
});

const modal = document.getElementById("video-modal");
const video = document.getElementById("project-video");
const closeModal = () => {
  modal.classList.remove("open");
  video.pause();
  video.removeAttribute("src");
  video.load();
};

document.querySelectorAll(".js-video").forEach((btn) => {
  btn.addEventListener("click", () => {
    video.src = btn.dataset.src;
    modal.classList.add("open");
    video.play().catch(() => {});
  });
});

document.getElementById("modal-close").addEventListener("click", closeModal);
modal.addEventListener("click", (event) => {
  if (event.target === modal) closeModal();
});
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeModal();
});

document.getElementById("contact-form").addEventListener("submit", (event) => {
  event.preventDefault();
  const data = new FormData(event.target);
  const name = data.get("name");
  const email = data.get("email");
  const message = data.get("message");
  const subject = encodeURIComponent(`Portfolio message from ${name}`);
  const body = encodeURIComponent(`${message}\n\nFrom: ${name} <${email}>`);
  window.location.href = `mailto:wilnaufi@gmail.com?subject=${subject}&body=${body}`;
});

